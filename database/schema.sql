-- VITRANO database schema draft
-- Apply only to a dedicated VITRANO Supabase project. Do not run on MarketMix or Universal Marketplace.
create extension if not exists pgcrypto;

create table if not exists public.categories (
  id uuid primary key default gen_random_uuid(),
  name text not null unique,
  slug text not null unique,
  sort_order integer not null default 0,
  is_visible boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.suppliers (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  contact_name text,
  phone text,
  messenger text,
  is_active boolean not null default true,
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.products (
  id uuid primary key default gen_random_uuid(),
  sku text unique,
  name text not null,
  slug text not null unique,
  description text,
  characteristics jsonb not null default '{}'::jsonb,
  category_id uuid references public.categories(id) on delete set null,
  image_urls text[] not null default '{}',
  main_image_url text,
  is_visible boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.supplier_offers (
  id uuid primary key default gen_random_uuid(),
  product_id uuid not null references public.products(id) on delete cascade,
  supplier_id uuid not null references public.suppliers(id) on delete restrict,
  purchase_cost numeric(12,2) check (purchase_cost is null or purchase_cost >= 0),
  retail_price numeric(12,2) check (retail_price is null or retail_price >= 0),
  availability text not null default 'check' check (availability in ('available','check','unavailable')),
  last_checked_at timestamptz,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(product_id, supplier_id)
);

create table if not exists public.customers (
  id uuid primary key default gen_random_uuid(),
  auth_user_id uuid unique references auth.users(id) on delete set null,
  full_name text not null,
  phone text not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.customer_addresses (
  id uuid primary key default gen_random_uuid(),
  customer_id uuid not null references public.customers(id) on delete cascade,
  carrier text not null check (carrier in ('nova_poshta','ukrposhta')),
  city text not null,
  branch text not null,
  recipient_name text,
  phone text,
  created_at timestamptz not null default now()
);

create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(),
  order_number bigint generated by default as identity unique,
  customer_id uuid references public.customers(id) on delete set null,
  customer_name text not null,
  customer_phone text not null,
  carrier text not null check (carrier in ('nova_poshta','ukrposhta')),
  city text not null,
  branch text not null,
  supplier_id uuid not null references public.suppliers(id) on delete restrict,
  status text not null default 'new' check (status in ('new','checking','confirmed','sent_to_supplier','shipped','delivered','cancelled','returned')),
  payment_status text not null default 'unpaid' check (payment_status in ('unpaid','paid','refunded','partially_refunded')),
  delivery_status text not null default 'not_shipped' check (delivery_status in ('not_shipped','shipped','delivered','returned')),
  ttn text,
  subtotal numeric(12,2) not null default 0 check (subtotal >= 0),
  delivery_cost numeric(12,2) check (delivery_cost is null or delivery_cost >= 0),
  customer_notes text,
  admin_notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.order_items (
  id uuid primary key default gen_random_uuid(),
  order_id uuid not null references public.orders(id) on delete cascade,
  product_id uuid references public.products(id) on delete set null,
  offer_id uuid references public.supplier_offers(id) on delete set null,
  product_name_snapshot text not null,
  sku_snapshot text,
  supplier_cost_snapshot numeric(12,2),
  unit_price numeric(12,2) not null check (unit_price >= 0),
  quantity integer not null check (quantity between 1 and 99),
  line_total numeric(12,2) generated always as (unit_price * quantity) stored
);

create table if not exists public.reviews (
  id uuid primary key default gen_random_uuid(),
  product_id uuid not null references public.products(id) on delete cascade,
  customer_id uuid references public.customers(id) on delete set null,
  order_id uuid references public.orders(id) on delete set null,
  rating integer not null check (rating between 1 and 5),
  body text,
  image_urls text[] not null default '{}',
  status text not null default 'pending' check (status in ('pending','published','rejected')),
  admin_reply text,
  created_at timestamptz not null default now()
);

create table if not exists public.promotions (
  id uuid primary key default gen_random_uuid(),
  title text not null,
  description text,
  code text unique,
  discount_type text not null check (discount_type in ('percent','fixed')),
  discount_value numeric(12,2) not null check (discount_value > 0),
  starts_at timestamptz,
  ends_at timestamptz,
  is_active boolean not null default false,
  created_at timestamptz not null default now()
);

create table if not exists public.admin_roles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  role text not null check (role in ('owner','admin','catalog_manager','order_manager','moderator')),
  created_at timestamptz not null default now()
);

create table if not exists public.audit_log (
  id bigint generated always as identity primary key,
  actor_user_id uuid references auth.users(id) on delete set null,
  action text not null,
  entity_type text not null,
  entity_id text,
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists products_category_visible_idx on public.products(category_id, is_visible);
create index if not exists supplier_offers_product_active_idx on public.supplier_offers(product_id, is_active, availability);
create index if not exists orders_created_idx on public.orders(created_at desc);
create index if not exists orders_status_created_idx on public.orders(status, created_at desc);
create index if not exists orders_customer_idx on public.orders(customer_id, created_at desc);
create index if not exists order_items_order_idx on public.order_items(order_id);
create index if not exists reviews_product_status_idx on public.reviews(product_id, status);

-- All exposed tables are RLS-protected. Public visitors can only read active public catalog data.
alter table public.categories enable row level security;
alter table public.suppliers enable row level security;
alter table public.products enable row level security;
alter table public.supplier_offers enable row level security;
alter table public.customers enable row level security;
alter table public.customer_addresses enable row level security;
alter table public.orders enable row level security;
alter table public.order_items enable row level security;
alter table public.reviews enable row level security;
alter table public.promotions enable row level security;
alter table public.admin_roles enable row level security;
alter table public.audit_log enable row level security;

create policy "Public can read visible categories" on public.categories for select to anon, authenticated using (is_visible = true);
create policy "Public can read visible products" on public.products for select to anon, authenticated using (is_visible = true);
create policy "Public can read active offers for visible products" on public.supplier_offers for select to anon, authenticated using (is_active = true and exists (select 1 from public.products p where p.id = product_id and p.is_visible = true));
-- Supplier contact details are private: no public SELECT policy on suppliers.
-- Expose only explicitly approved public supplier fields through a reviewed view/API when needed.
create policy "Public can read published reviews" on public.reviews for select to anon, authenticated using (status = 'published');
create policy "Public can read active promotions" on public.promotions for select to anon, authenticated using (is_active = true and (starts_at is null or starts_at <= now()) and (ends_at is null or ends_at >= now()));

-- No public write policies are added for orders, customers, admin roles, finance or audit logs.
-- Checkout must be implemented with a server-side Edge Function that validates prices,
-- supplier consistency, availability, input fields and rate limits before inserting orders.
-- Admin writes require authenticated users and role checks; do not expose service_role keys.
